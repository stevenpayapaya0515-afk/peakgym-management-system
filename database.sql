-- ============================================
-- MEMBERSHIP HISTORY
-- ============================================

-- View all membership periods
SELECT
    ms.id AS membership_id,
    m.id AS member_id,
    m.full_name,
    ms.start_date,
    ms.due_date,
    ms.created_at
FROM memberships AS ms
INNER JOIN members AS m
    ON m.id = ms.member_id
ORDER BY m.full_name, ms.start_date DESC, ms.id DESC;

-- View history for one member
-- Replace 1 with the actual member ID.
SELECT
    m.full_name,
    ms.id AS membership_id,
    ms.start_date,
    ms.due_date
FROM memberships AS ms
INNER JOIN members AS m
    ON m.id = ms.member_id
WHERE m.id = 1
ORDER BY ms.start_date DESC, ms.id DESC;


-- ============================================
-- MEMBERSHIP DATE REFERENCE
-- Philippine date, independent of MySQL timezone
-- Run before the status and count queries below
-- ============================================

SET @today = DATE(
    DATE_ADD(UTC_TIMESTAMP(), INTERVAL 8 HOUR)
);


-- ============================================
-- STATUS OF EACH MEMBERSHIP PERIOD
-- ============================================

SELECT
    m.full_name,
    ms.id AS membership_id,
    ms.start_date,
    ms.due_date,
    CASE
        WHEN ms.start_date > @today THEN 'Upcoming'
        WHEN ms.due_date < @today THEN 'Expired'
        ELSE 'Active'
    END AS period_status
FROM memberships AS ms
INNER JOIN members AS m
    ON m.id = ms.member_id
ORDER BY m.full_name, ms.start_date DESC;


-- ============================================
-- CURRENT STATUS OF EACH MEMBER
-- Checks all periods, including renewals
-- ============================================

SELECT
    m.id,
    m.full_name,
    CASE
        WHEN MAX(
            CASE
                WHEN ms.start_date <= @today
                 AND ms.due_date >= @today
                THEN 1
                ELSE 0
            END
        ) = 1 THEN 'Active'

        WHEN MAX(
            CASE
                WHEN ms.start_date > @today
                THEN 1
                ELSE 0
            END
        ) = 1 THEN 'Upcoming'

        WHEN COUNT(ms.id) = 0 THEN 'No membership'

        ELSE 'Expired'
    END AS membership_status
FROM members AS m
LEFT JOIN memberships AS ms
    ON ms.member_id = m.id
GROUP BY m.id, m.full_name
ORDER BY m.full_name;

-- Membership status is calculated when queried.
-- No scheduled UPDATE or stored status column is required.


-- ============================================
-- MEMBERSHIP DASHBOARD COUNTS
-- Counts members once, even with several renewals
-- Matches the dashboard's existing counting rules
-- ============================================

SELECT
    COUNT(*) AS total_members,
    COALESCE(SUM(summary.is_active), 0) AS active_memberships,
    COALESCE(SUM(summary.expires_today), 0) AS expiring_today,
    COUNT(
        CASE
            WHEN summary.last_due < @today THEN 1
        END
    ) AS expired_memberships
FROM (
    SELECT
        m.id,
        MAX(
            CASE
                WHEN ms.start_date <= @today
                 AND ms.due_date >= @today
                THEN 1
                ELSE 0
            END
        ) AS is_active,
        MAX(
            CASE
                WHEN ms.start_date <= @today
                 AND ms.due_date = @today
                THEN 1
                ELSE 0
            END
        ) AS expires_today,
        MAX(ms.due_date) AS last_due
    FROM members AS m
    LEFT JOIN memberships AS ms
        ON ms.member_id = m.id
    GROUP BY m.id
) AS summary;

-- Expiring today is included in Active memberships.
-- Members with upcoming renewals are not counted as expired.
-- Total members also includes members with no membership period.


-- ============================================
-- LOGIN ATTEMPTS AND LOCKOUT
-- ============================================

-- View login status
SELECT username, role, failed_attempts, locked_until
FROM users
ORDER BY username;

-- Check one administrator
SELECT username, failed_attempts, locked_until
FROM users
WHERE username = 'admin.peakgym';

-- Remaining login lockout time
-- NOW() matches the existing login's database lockout logic.
SELECT
    username,
    failed_attempts,
    locked_until,
    COALESCE(
        GREATEST(
            0,
            TIMESTAMPDIFF(SECOND, NOW(), locked_until)
        ),
        0
    ) AS remaining_seconds
FROM users
WHERE username = 'admin.peakgym';


