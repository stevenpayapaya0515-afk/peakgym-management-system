-- ============================================
-- USERS TABLE
-- Administrator and staff accounts
-- ============================================

CREATE TABLE users (
    id INT AUTO_INCREMENT PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    email VARCHAR(100) NOT NULL,
    password VARCHAR(255) NOT NULL,
    role ENUM('admin', 'staff') NOT NULL DEFAULT 'staff',
    is_active TINYINT(1) NOT NULL DEFAULT 1,
    failed_attempts INT NOT NULL DEFAULT 0,
    locked_until DATETIME NULL
) ENGINE = InnoDB;

-- password stores the hash generated by PHP password_hash().
-- Staff accounts are created through Staff Management.
-- A new installation needs an initial administrator account.
-- Never insert a plain-text password.


-- ============================================
-- MEMBERS TABLE
-- Gym members are separate from login accounts
-- ============================================

CREATE TABLE members (
    id INT AUTO_INCREMENT PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    photo VARCHAR(255) NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE = InnoDB;

-- photo stores the generated photo filename.
-- The actual image is stored in the private upload directory.
-- Members do not need a users account.


-- ============================================
-- MEMBERSHIPS TABLE
-- Each renewal creates another membership period
-- ============================================

CREATE TABLE memberships (
    id INT AUTO_INCREMENT PRIMARY KEY,
    member_id INT NOT NULL,
    start_date DATE NOT NULL,
    due_date DATE NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    INDEX idx_membership_member_dates (
        member_id,
        start_date,
        due_date
    ),

    CONSTRAINT fk_memberships_member
        FOREIGN KEY (member_id)
        REFERENCES members(id)
        ON DELETE CASCADE
) ENGINE = InnoDB;

-- PHP validates that due_date is not before start_date.
-- Add and Renew calculate one calendar month in PHP.
-- The due date is inclusive:
-- A membership due October 9 remains active on October 9.
-- It becomes expired on October 10 unless another period applies.
--
-- ON DELETE CASCADE removes membership history when a member
-- is permanently deleted.
-- Deleting the member's photo file is handled by PHP.


